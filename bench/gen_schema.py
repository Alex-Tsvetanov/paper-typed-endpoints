"""Deterministic proto3 schemas and user programs for the compile curves (design note section 4).

Shapes:
  wide  one message with N fields cycling through the 15 scalar types and one enum, and one
        service with one rpc.
  many  N/8 messages of 8 fields each; every odd-numbered message holds a field of the previous
        message type; one service with one rpc per message.

Usage:
  gen_schema.py schema  --shape wide|many --n N            print the .proto
  gen_schema.py reflect --shape wide|many --n N --proto P  print the reflection user program,
                                                           which #embeds the .proto at path P
  gen_schema.py protoc  --shape wide|many --n N            print the protoc user program, which
                                                           includes protoc's schema.pb.h
"""
from __future__ import annotations

import argparse
import sys

SCALARS = [
    "double", "float", "int64", "uint64", "int32", "fixed64", "fixed32", "bool",
    "string", "bytes", "uint32", "sfixed32", "sfixed64", "sint32", "sint64",
]
KINDS = SCALARS + ["Kind"]  # 16 field kinds; the enum is the last
PACKAGE = "bench"
FIELDS_PER_MESSAGE = 8


def messages(shape: str, n: int, nesting: bool = True) -> list[tuple[str, list[tuple[str, str, int]]]]:
    """Returns (message name, [(type, field name, number)]) in declaration order."""
    if n < FIELDS_PER_MESSAGE or n % FIELDS_PER_MESSAGE != 0:
        raise SystemExit("n must be a positive multiple of 8")
    if n > 18999:
        raise SystemExit("n must stay below the implementation range 19000 to 19999")
    if shape == "wide":
        return [("Wide", [(KINDS[i % len(KINDS)], f"f{i + 1}", i + 1) for i in range(n)])]
    out = []
    for m in range(n // FIELDS_PER_MESSAGE):
        fields = []
        for k in range(FIELDS_PER_MESSAGE):
            kind = KINDS[(m * FIELDS_PER_MESSAGE + k) % len(KINDS)]
            if nesting and m % 2 == 1 and k == FIELDS_PER_MESSAGE - 1:
                kind = f"M{m - 1}"
            fields.append((kind, f"f{k + 1}", k + 1))
        out.append((f"M{m}", fields))
    return out


def schema(shape: str, n: int, nesting: bool = True, service: bool = True) -> str:
    lines = ['syntax = "proto3";', f"package {PACKAGE};", "", "enum Kind {", "  KIND_ZERO = 0;", "  KIND_ONE = 1;", "}", ""]
    msgs = messages(shape, n, nesting)
    for name, fields in msgs:
        lines.append(f"message {name} {{")
        lines += [f"  {t} {f} = {num};" for t, f, num in fields]
        lines += ["}", ""]
    if service:
        lines.append("service Svc {")
        lines += [f"  rpc Call{name}({name}) returns ({name});" for name, _ in msgs]
        lines.append("}")
    return "\n".join(lines) + "\n"


def reflect_user(shape: str, n: int, proto: str) -> str:
    msgs = messages(shape, n)
    out = [
        "// Generated by bench/gen_schema.py. The reflection generator's user program: it",
        "// synthesizes every message, binds a handler for every rpc, and encodes and decodes",
        "// every message once, so the codec is instantiated for all of them.",
        "#include <cstdio>",
        "#include <vector>",
        '#include "tep/reflect.hpp"',
        "",
        "struct schema {",
        "    static constexpr char data[] = {",
        f'#embed "{proto}"',
        "        , '\\0'};",
        "    static constexpr std::string_view text{data, sizeof data - 1};",
        "};",
        "consteval { tep::define_messages<schema>(); }",
        "",
    ]
    out += [f'using {name} = tep::message_t<schema, "{PACKAGE}.{name}">;' for name, _ in msgs]
    out += ["", "struct handler {"]
    out += [f"    {name} Call{name}(const {name}& q) {{ return q; }}" for name, _ in msgs]
    out += ["};", "", "int main(int argc, char**) {", "    handler h;",
            "    tep::endpoint<schema, \"bench.Svc\", handler> ep{h};",
            "    std::vector<std::byte> response;", "    std::size_t total = 0;"]
    for name, _ in msgs:
        out += [
            "    {",
            f"        {name} m{{}};",
            "        const auto bytes = tep::encode(m);",
            f"        total += tep::decode<{name}>(bytes).has_value() ? bytes.size() : 1;",
            f'        if (argc > 1) total += static_cast<std::size_t>(ep.invoke("/bench.Svc/Call{name}", bytes, response));',
            "    }",
        ]
    out += ['    std::printf("%zu\\n", total);', "    return 0;", "}"]
    return "\n".join(out) + "\n"


def protoc_user(shape: str, n: int) -> str:
    """The protoc generator's user program: the same work as reflect_user, written against the
    classes protoc generates, with a hand-written route table of the same shape."""
    msgs = messages(shape, n)
    out = [
        "// Generated by bench/gen_schema.py. The protoc generator's user program: it encodes and",
        "// decodes every message once and routes every rpc through a hand-written table, the same",
        "// work as the reflection generator's user program.",
        "#include <cstdio>",
        "#include <string>",
        "#include <string_view>",
        "",
        '#include "schema.pb.h"',
        "",
        "namespace {",
        "",
        "struct handler {",
    ]
    out += [f"    {PACKAGE}::{name} Call{name}(const {PACKAGE}::{name}& q) {{ return q; }}" for name, _ in msgs]
    out += [
        "};",
        "",
        "using call_fn = bool (*)(handler&, std::string_view, std::string&);",
        "",
        "template <class Req, class Resp, Resp (handler::*Method)(const Req&)>",
        "bool call(handler& h, std::string_view request, std::string& response) {",
        "    Req q;",
        "    if (!q.ParseFromArray(request.data(), static_cast<int>(request.size()))) return false;",
        "    const Resp r = (h.*Method)(q);",
        "    response.clear();",
        "    return r.SerializeToString(&response);",
        "}",
        "",
        "struct route {",
        "    std::string_view path;",
        "    call_fn fn;",
        "};",
        "",
        "constexpr route routes[] = {",
    ]
    out += [
        f'    {{"/{PACKAGE}.Svc/Call{name}", &call<{PACKAGE}::{name}, {PACKAGE}::{name}, &handler::Call{name}>}},'
        for name, _ in msgs
    ]
    out += [
        "};",
        "",
        "}  // namespace",
        "",
        "int main(int argc, char**) {",
        "    handler h;",
        "    std::string response;",
        "    std::size_t total = 0;",
    ]
    for name, _ in msgs:
        out += [
            "    {",
            f"        {PACKAGE}::{name} m;",
            "        std::string bytes;",
            "        if (!m.SerializeToString(&bytes)) return 1;",
            f"        {PACKAGE}::{name} back;",
            "        total += back.ParseFromString(bytes) ? bytes.size() : 1;",
            "        if (argc > 1)",
            "            for (const route& r : routes)",
            f'                if (r.path == "/{PACKAGE}.Svc/Call{name}") total += r.fn(h, bytes, response) ? 0u : 1u;',
            "    }",
        ]
    out += ['    std::printf("%zu\\n", total);', "    return 0;", "}"]
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("what", choices=["schema", "reflect", "protoc"])
    ap.add_argument("--shape", choices=["wide", "many"], required=True)
    ap.add_argument("--n", type=int, required=True)
    ap.add_argument("--proto", default="schema.proto")
    ap.add_argument("--no-nesting", action="store_true", help="no field of another message type")
    ap.add_argument("--no-service", action="store_true", help="no service, messages only")
    args = ap.parse_args(argv[1:])
    if args.what == "schema":
        text = schema(args.shape, args.n, not args.no_nesting, not args.no_service)
    elif args.what == "protoc":
        text = protoc_user(args.shape, args.n)
    else:
        text = reflect_user(args.shape, args.n, args.proto)
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
